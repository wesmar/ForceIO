# ForceIO - deterministic Release x86 build + driver checksum patching
# WESMAR Marek Wesolowski

[CmdletBinding()]
param(
    [switch]$Clean,
    [switch]$NoBuild
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$ProjectRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$ProjectFile = Join-Path $ProjectRoot "src\ForceIO.vcxproj"
$OutputDir   = Join-Path $ProjectRoot "bin"
$OutputExe   = Join-Path $OutputDir "ForceIO.exe"

# Driver checksum targets (from IObitUnlocker.sys+0x3DC7)
$TARGET_XOR = 0x2B
$TARGET_ALT = 0x00A88677

$IcoBuilder  = Join-Path $ProjectRoot 'IcoBuilder'
$IconDir     = Join-Path $ProjectRoot 'ICON'

$TransientDirs = @(
    (Join-Path $ProjectRoot ".vs"),
    (Join-Path $ProjectRoot "obj"),
    (Join-Path $ProjectRoot "x64"),
    (Join-Path $ProjectRoot "Win32"),
    (Join-Path $ProjectRoot "src\.vs"),
    (Join-Path $ProjectRoot "src\obj"),
    (Join-Path $ProjectRoot "src\x64"),
    (Join-Path $ProjectRoot "src\Win32")
)

function Build-PayloadIcon {
    $baseIcon  = Join-Path $IcoBuilder 'kvc.ico'
    $driverDat = Join-Path $IcoBuilder 'forceio.dat'
    $outIcon   = Join-Path $IconDir 'kvc.ico'

    foreach ($f in $baseIcon, $driverDat) {
        if (-not (Test-Path -LiteralPath $f)) {
            throw "Required file not found: $f"
        }
    }

    $iconBytes  = [System.IO.File]::ReadAllBytes($baseIcon)
    $headerSize = $iconBytes.Length

    $tmpDir = [System.IO.Path]::Combine(
        [System.IO.Path]::GetTempPath(),
        "fio_pack_$([System.IO.Path]::GetRandomFileName())")
    New-Item -ItemType Directory -Force -Path $tmpDir | Out-Null

    try {
        $tmpDat = Join-Path $tmpDir 'forceio.dat'
        Copy-Item -LiteralPath $driverDat -Destination $tmpDat -Force

        $ddf = @"
.Set CabinetNameTemplate=forceio.cab
.Set DiskDirectoryTemplate=$tmpDir
.Set CompressionType=LZX
.Set CompressionMemory=21
.Set MaxCabinetSize=0
.Set Cabinet=on
.Set Compress=on
"$tmpDat" forceio.dat
"@
        $ddfPath = Join-Path $tmpDir 'pack.ddf'
        [System.IO.File]::WriteAllText($ddfPath, $ddf, [System.Text.Encoding]::ASCII)

        $p = Start-Process makecab.exe `
                 -ArgumentList '/F', "`"$ddfPath`"" `
                 -Wait -PassThru -NoNewWindow -WorkingDirectory $tmpDir
        if ($p.ExitCode -ne 0) {
            throw "makecab.exe failed (exit $($p.ExitCode))"
        }

        $cabPath = Join-Path $tmpDir 'forceio.cab'
        if (-not (Test-Path -LiteralPath $cabPath)) {
            throw "CAB not produced: $cabPath"
        }

        $cabBytes = [System.IO.File]::ReadAllBytes($cabPath)
        $combined = [byte[]]::new($headerSize + $cabBytes.Length)
        [Array]::Copy($iconBytes, 0, $combined, 0, $headerSize)
        [Array]::Copy($cabBytes, 0, $combined, $headerSize, $cabBytes.Length)

        if (-not (Test-Path -LiteralPath $IconDir)) {
            New-Item -ItemType Directory -Force -Path $IconDir | Out-Null
        }
        [System.IO.File]::WriteAllBytes($outIcon, $combined)

        Write-Host ("  Driver : {0:N0} B -> {1:N0} B CAB" -f (Get-Item $driverDat).Length, $cabBytes.Length) -ForegroundColor DarkGray
        Write-Host ("  Icon   : {0:N0} B header + {1:N0} B CAB = {2:N0} B total" -f $headerSize, $cabBytes.Length, $combined.Length) -ForegroundColor DarkGray

        $genH = @"
// Auto-generated by build.ps1 — do not edit manually.
// Byte count of IcoBuilder\kvc.ico; CAB payload begins at this offset.
#pragma once
#define ICON_HEADER_SIZE $headerSize
"@
        [System.IO.File]::WriteAllText((Join-Path $ProjectRoot 'src\GenIconSize.h'), $genH)
        Write-Host "  GenIconSize.h : ICON_HEADER_SIZE = $headerSize" -ForegroundColor DarkGray
    }
    finally {
        Remove-Item $tmpDir -Recurse -Force -ErrorAction SilentlyContinue
    }
}

function Resolve-MSBuild {
    # 1. Official Microsoft locator tool: vswhere (queries newest instance)
    $vswhereCandidates = @(
        (Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\Installer\vswhere.exe"),
        (Join-Path $env:ProgramFiles "Microsoft Visual Studio\Installer\vswhere.exe")
    )
    $vswhereCmd = Get-Command vswhere.exe -ErrorAction SilentlyContinue
    if ($vswhereCmd) {
        $vswhereCandidates += $vswhereCmd.Source
    }

    $vswhere = $vswhereCandidates | Where-Object { $_ -and (Test-Path -LiteralPath $_) } | Select-Object -First 1
    if ($vswhere) {
        $installationPath = & $vswhere -latest -prerelease -products * -requires Microsoft.Component.MSBuild -property installationPath
        if ($LASTEXITCODE -eq 0 -and $installationPath) {
            $candidates = @(
                (Join-Path $installationPath "MSBuild\Current\Bin\MSBuild.exe"),
                (Join-Path $installationPath "MSBuild\Current\Bin\amd64\MSBuild.exe"),
                (Join-Path $installationPath "MSBuild\15.0\Bin\MSBuild.exe")
            )
            foreach ($candidate in $candidates) {
                if (Test-Path -LiteralPath $candidate) {
                    return $candidate
                }
            }
        }

        # Secondary search using vswhere -find
        $foundPaths = & $vswhere -latest -prerelease -products * -requires Microsoft.Component.MSBuild -find MSBuild\**\Bin\MSBuild.exe
        if ($LASTEXITCODE -eq 0 -and $foundPaths) {
            $first = ($foundPaths -split "\r?\n" | Where-Object { $_ -and (Test-Path -LiteralPath $_) } | Select-Object -First 1)
            if ($first) {
                return $first
            }
        }
    }

    # 2. Filesystem search across standard Program Files roots, sorted descending by version
    $searchRoots = @(
        $env:ProgramFiles,
        ${env:ProgramFiles(x86)}
    ) | Where-Object { $_ -and (Test-Path -LiteralPath $_) } | Select-Object -Unique

    $discoveredVsDirs = @()
    foreach ($root in $searchRoots) {
        $vsRoot = Join-Path $root "Microsoft Visual Studio"
        if (Test-Path -LiteralPath $vsRoot) {
            $discoveredVsDirs += Get-ChildItem -LiteralPath $vsRoot -Directory -ErrorAction SilentlyContinue
        }
    }

    # Sort descending so newest Visual Studio version (e.g. 18, 17...) is evaluated first
    $sortedVsDirs = $discoveredVsDirs | Sort-Object {
        $cleanNum = ($_.Name -replace '[^\d.]', '')
        if ($cleanNum) { [version]$cleanNum } else { [version]'0.0' }
    } -Descending

    $editions = @("Enterprise", "Professional", "Community", "BuildTools", "Preview")
    foreach ($dir in $sortedVsDirs) {
        foreach ($edition in $editions) {
            $candidates = @(
                (Join-Path $dir.FullName "$edition\MSBuild\Current\Bin\MSBuild.exe"),
                (Join-Path $dir.FullName "$edition\MSBuild\Current\Bin\amd64\MSBuild.exe"),
                (Join-Path $dir.FullName "$edition\MSBuild\15.0\Bin\MSBuild.exe")
            )
            foreach ($candidate in $candidates) {
                if (Test-Path -LiteralPath $candidate) {
                    return $candidate
                }
            }
        }
    }

    # 3. Environment PATH fallback
    $pathCmd = Get-Command msbuild.exe -ErrorAction SilentlyContinue
    if ($pathCmd) {
        return $pathCmd.Source
    }

    throw "MSBuild not found. Install Visual Studio or Build Tools with Desktop C++ workload."
}

function Remove-TransientDirs {
    foreach ($dir in $TransientDirs) {
        if (Test-Path -LiteralPath $dir) {
            Remove-Item -LiteralPath $dir -Recurse -Force -ErrorAction SilentlyContinue
        }
    }
}

function Assert-CleanLayout {
    foreach ($dir in $TransientDirs) {
        if (Test-Path -LiteralPath $dir) {
            throw "Transient directory still present: $dir"
        }
    }
    $remainingObj = @(Get-ChildItem -LiteralPath $ProjectRoot -Recurse -Filter "*.obj" -File -ErrorAction SilentlyContinue)
    if ($remainingObj.Length -gt 0) {
        throw ("Transient obj files still present: " + (($remainingObj | Select-Object -ExpandProperty FullName) -join ", "))
    }
}

function Assert-ProjectExists {
    if (-not (Test-Path -LiteralPath $ProjectFile)) {
        throw "Project file not found: $ProjectFile"
    }
}

function Invoke-Build {
    param([string]$MSBuildPath)

    if (-not (Test-Path $OutputDir)) {
        New-Item -ItemType Directory -Path $OutputDir | Out-Null
    }

    $arguments = @(
        $ProjectFile
        "/t:Build"
        "/p:Configuration=Release;Platform=Win32"
        "/m"
        "/nr:false"
        "/v:minimal"
    )

    Write-Host "[*] Building ForceIO (Release x86)..." -ForegroundColor Cyan
    & $MSBuildPath @arguments
    if ($LASTEXITCODE -ne 0) {
        throw "MSBuild failed with exit code $LASTEXITCODE."
    }

    if (-not (Test-Path $OutputExe)) {
        throw "Build completed but output was not produced: $OutputExe"
    }
}

function Get-Checksums {
    param([byte[]]$Data)

    [int]$xor = 0
    [long]$alt = 0

    for ($i = 0; $i -lt $Data.Length; $i++) {
        $xor = $xor -bxor $Data[$i]
        if ($i % 2 -eq 0) { $alt += $Data[$i] }
        else               { $alt -= $Data[$i] }
    }

    # Handle negative ALT values - mask to unsigned 32-bit
    $altMasked = $alt -band 0xFFFFFFFFL
    if ($altMasked -lt 0) { $altMasked += 4294967296 }

    return @{
        XOR = $xor -band 0xFF
        ALT = [long]$altMasked
    }
}

function Invoke-ChecksumPatch {
    Write-Host "[*] Patching binary checksums..." -ForegroundColor Cyan

    $data = [System.IO.File]::ReadAllBytes($OutputExe)

    if ($data.Length % 2 -ne 0) {
        $data += [byte]0
    }

    $cs = Get-Checksums -Data $data
    Write-Host ("  Current:  XOR=0x{0:X2}  ALT=0x{1:X8}" -f $cs.XOR, $cs.ALT) -ForegroundColor DarkGray
    Write-Host ("  Target:   XOR=0x{0:X2}  ALT=0x{1:X8}" -f $TARGET_XOR, $TARGET_ALT) -ForegroundColor DarkGray

    if ($cs.XOR -eq $TARGET_XOR -and $cs.ALT -eq $TARGET_ALT) {
        Write-Host "[+] Checksums already match." -ForegroundColor Green
        return
    }

    # Unsigned modular difference: how much to ADD to reach target (mod 2^32)
    [long]$alt_need = ([long]$TARGET_ALT - [long]$cs.ALT + 4294967296) % 4294967296
    [int]$bulk = [Math]::Floor($alt_need / 255)
    [int]$remain = [int]($alt_need - [long]$bulk * 255)

    [int]$xor_after = $cs.XOR
    if ($bulk % 2 -ne 0) { $xor_after = $xor_after -bxor 0xFF }
    [int]$xor_need = $xor_after -bxor $TARGET_XOR

    Write-Host "  Bulk pairs: $bulk, remainder: $remain, XOR fix: 0x$($xor_need.ToString('X2'))" -ForegroundColor DarkGray

    $solution = $null
    for ($b0 = 0; $b0 -lt 256 -and -not $solution; $b0++) {
        for ($b2 = 0; $b2 -lt 256 -and -not $solution; $b2++) {
            $odd_sum = $b0 + $b2 - $remain
            $odd_xor = $b0 -bxor $b2 -bxor $xor_need
            if ($odd_sum -lt 0 -or $odd_sum -gt 510) { continue }
            $diff = $odd_sum - $odd_xor
            if ($diff -lt 0 -or $diff % 2 -ne 0) { continue }
            for ($b1 = 0; $b1 -lt 256; $b1++) {
                $b3 = $odd_sum - $b1
                if ($b3 -ge 0 -and $b3 -le 255 -and (($b1 -bxor $b3) -eq $odd_xor)) {
                    $solution = @($b0, $b1, $b2, $b3)
                    break
                }
            }
        }
    }

    if (-not $solution) {
        throw "Cannot find checksum correction bytes."
    }

    Write-Host ("  Correction: [{0}]" -f ($solution -join ', ')) -ForegroundColor DarkGray

    $padding = New-Object byte[] ($bulk * 2)
    for ($i = 0; $i -lt $bulk; $i++) {
        $padding[$i * 2]     = 0xFF
        $padding[$i * 2 + 1] = 0x00
    }
    $tail = [byte[]]$solution

    $patched = New-Object byte[] ($data.Length + $padding.Length + $tail.Length)
    [Array]::Copy($data, 0, $patched, 0, $data.Length)
    [Array]::Copy($padding, 0, $patched, $data.Length, $padding.Length)
    [Array]::Copy($tail, 0, $patched, $data.Length + $padding.Length, $tail.Length)

    $vcs = Get-Checksums -Data $patched
    if ($vcs.XOR -ne $TARGET_XOR -or $vcs.ALT -ne $TARGET_ALT) {
        throw ("Verification failed: XOR=0x{0:X2} ALT=0x{1:X8}" -f $vcs.XOR, $vcs.ALT)
    }

    [System.IO.File]::WriteAllBytes($OutputExe, $patched)
    $appended = $patched.Length - $data.Length
    Write-Host ("[+] Patched: {0:N0} bytes (+{1:N0} checksum correction)" -f $patched.Length, $appended) -ForegroundColor Green
}

try {
    Assert-ProjectExists
    $msbuild = Resolve-MSBuild
    Write-Host "[*] Using MSBuild: $msbuild" -ForegroundColor Cyan

    Remove-TransientDirs
    Assert-CleanLayout

    if ($Clean -or $NoBuild) {
        if ($Clean -and (Test-Path -LiteralPath $OutputExe)) {
            Remove-Item -LiteralPath $OutputExe -Force -ErrorAction SilentlyContinue
            Write-Host "  [-] Removed output: $OutputExe" -ForegroundColor DarkGray
        }
        Write-Host "[+] Clean completed." -ForegroundColor Green
        exit 0
    }

    Write-Host "[*] Packing driver into icon..." -ForegroundColor Cyan
    Build-PayloadIcon

    Invoke-Build -MSBuildPath $msbuild

    # Purge obj and transient build outputs immediately after compilation
    Remove-TransientDirs
    Assert-CleanLayout

    # Verify no CRT dependencies - pure kernel32/advapi32/cabinet only
    Write-Host "[*] Verifying dependencies..." -ForegroundColor Cyan
    $vsRoot = Split-Path (Split-Path (Split-Path (Split-Path $msbuild)))
    $dumpbin = Get-ChildItem "$vsRoot\VC\Tools\MSVC\*\bin\Hostx64\x86\dumpbin.exe" -ErrorAction SilentlyContinue |
               Sort-Object FullName -Descending | Select-Object -First 1
    if (-not $dumpbin) {
        $dumpbin = Get-ChildItem "$vsRoot\VC\Tools\MSVC\*\bin\Hostx86\x86\dumpbin.exe" -ErrorAction SilentlyContinue |
                   Sort-Object FullName -Descending | Select-Object -First 1
    }
    if ($dumpbin) {
        $deps = & $dumpbin.FullName /NOLOGO /DEPENDENTS $OutputExe 2>&1 | Out-String
        if ($LASTEXITCODE -ne 0) { throw "dumpbin.exe failed: $LASTEXITCODE" }
        $allowed = @("KERNEL32.dll", "ADVAPI32.dll", "CABINET.dll")
        $dllLines = ($deps -split "`n") | Where-Object { $_ -match '^\s+\S+\.dll\s*$' } | ForEach-Object { $_.Trim() }
        if (!$dllLines) { throw 'Dependency verification did not return any DLL names.' }
        $forbidden = $dllLines | Where-Object { $_ -notin $allowed }
        if ($forbidden) {
            throw "Forbidden CRT dependencies detected: $($forbidden -join ', ')"
        }
        Write-Host ("  Dependencies: {0}" -f ($dllLines -join ', ')) -ForegroundColor DarkGray
        Write-Host "[+] No CRT - clean." -ForegroundColor Green
    } else {
        Write-Host "  [!] dumpbin not found, skipping dependency check." -ForegroundColor Yellow
    }

    Invoke-ChecksumPatch

    # Final cleanup of obj
    Remove-TransientDirs
    Assert-CleanLayout

    $ts = Get-Date "2030-01-01 00:00:00"
    $f = Get-Item $OutputExe
    $f.CreationTime = $ts
    $f.LastWriteTime = $ts

    Write-Host "`n[+] Build complete: $OutputExe" -ForegroundColor Green
    Write-Host ("[+] Final size: {0:N0} bytes" -f (Get-Item $OutputExe).Length) -ForegroundColor Green
    exit 0
}
catch {
    Write-Host "[!] $_" -ForegroundColor Red
    exit 1
}
finally {
    if (-not $NoBuild -and -not $Clean) {
        Remove-TransientDirs
        try {
            Assert-CleanLayout
        } catch {
            Write-Warning "Clean layout check warning: $_"
        }
    }
}
